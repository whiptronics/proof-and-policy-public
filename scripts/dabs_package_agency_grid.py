"""DABS's Type 2 / Type 3 package agency compensation grid, read from the published PDF.

Writes web/src/lib/packageAgencyGrid.generated.ts: the fifteen annual bottle steps, the seven average bottle price
classes and the fixed annual dollars DABS pays a package agency in each cell. The grid is read from the PDF's own
table (pdfplumber), not typed by hand.

Run:  python -B scripts/dabs_package_agency_grid.py          (write the file)
      python -B scripts/dabs_package_agency_grid.py --check  (exit 1 if the committed file differs)
The PDF is found under ALCOHOL_DATA_HOME/data/raw (default: this checkout), asset utah_dabs_pa_compensation_fy2027.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pdfplumber

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from alcohol_data.paths import RAW_DIR  # noqa: E402

ASSET = "utah_dabs_pa_compensation_fy2027"
OUT = ROOT / "web" / "src" / "lib" / "packageAgencyGrid.generated.ts"
TITLE = "Type 2 / Type 3 Package Agency Compensation Grid - Static Annual Dollar Amounts"


def _int(s: str) -> int:
    return int(re.sub(r"[^\d]", "", s))


def read(raw: Path = RAW_DIR) -> dict:
    files = sorted((raw / ASSET).glob("*.pdf"))
    if len(files) != 1:
        raise FileNotFoundError(f"{ASSET}: expected one PDF in {raw / ASSET}, found {len(files)}")
    with pdfplumber.open(files[0]) as pdf:
        if len(pdf.pages) != 1:
            raise ValueError(f"{ASSET}: expected one page, found {len(pdf.pages)}")
        page = pdf.pages[0]
        text = page.extract_text() or ""
        rows = [r for t in page.extract_tables() for r in t]
    rev = re.search(r"Rev\.\s*(\d\d-\d{4})", text)
    if TITLE not in text or not rev:
        raise ValueError(f"{ASSET}: title or revision line not found; the layout changed")
    head = next(i for i, r in enumerate(rows) if r and r[0] == "Step")
    classes = []
    for cell in rows[head][2:]:
        m = re.fullmatch(r"([A-G]) \((<|>)?\$([\d.]+)(?:-\$([\d.]+))?\)", cell)
        if not m:
            raise ValueError(f"{ASSET}: price class header {cell!r} not understood")
        letter, sign, a, b = m.groups()
        lo, hi = (
            (None, float(a)) if sign == "<" else (float(a), None) if sign == ">" else (float(a), float(b))
        )
        classes.append({"id": letter, "minPrice": lo, "maxPrice": hi})
    steps = []
    for r in rows[head + 1 :]:
        q = r[1]
        if q.startswith("<"):
            lo, hi = 0, _int(q) - 1
        elif q.startswith(">"):
            lo, hi = _int(q) + 1, None
        else:
            a, b = q.split("-")
            lo, hi = _int(a), _int(b)
        pay = [_int(c) for c in r[2:]]
        if len(pay) != len(classes):
            raise ValueError(f"{ASSET}: step {r[0]} has {len(pay)} amounts for {len(classes)} classes")
        steps.append({"step": int(r[0]), "minBottles": lo, "maxBottles": hi, "pay": pay})
    if [s["step"] for s in steps] != list(range(1, len(steps) + 1)):
        raise ValueError(f"{ASSET}: steps are not numbered 1..{len(steps)}")
    for prev, s in zip(steps, steps[1:], strict=False):
        if s["minBottles"] != prev["maxBottles"] + 1:
            raise ValueError(f"{ASSET}: a gap or overlap between steps {prev['step']} and {s['step']}")
    return {"revision": rev.group(1), "classes": classes, "steps": steps}


def render(grid: dict) -> str:
    classes = ",\n".join(
        f'    {{ id: "{c["id"]}", minPrice: {json.dumps(c["minPrice"])}, maxPrice: {json.dumps(c["maxPrice"])} }}'
        for c in grid["classes"]
    )
    steps = ",\n".join(
        f"    {{ step: {s['step']}, minBottles: {s['minBottles']}, maxBottles: {json.dumps(s['maxBottles'])}, "
        f"pay: [{', '.join(str(p) for p in s['pay'])}] }}"
        for s in grid["steps"]
    )
    return (
        "// Generated by scripts/dabs_package_agency_grid.py from DABS's published PDF; do not edit by hand.\n"
        "// tests/test_dabs_package_agency_grid.py fails when this file differs from what the script writes.\n"
        "export const PACKAGE_AGENCY_GRID = {\n"
        f'  source: "{ASSET}",\n'
        f'  title: "{TITLE}",\n'
        f'  revision: "{grid["revision"]}",\n'
        f"  classes: [\n{classes},\n  ],\n"
        f"  steps: [\n{steps},\n  ],\n"
        "} as const;\n"
    )


def main(argv: list[str]) -> int:
    text = render(read())
    if "--check" in argv:
        same = OUT.read_text(encoding="utf-8") == text
        print("packageAgencyGrid.generated.ts " + ("matches" if same else "DIFFERS from the PDF"))
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
