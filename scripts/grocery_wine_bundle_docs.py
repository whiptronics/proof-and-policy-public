"""Reference files for the grocery-wine graph package: data dictionary, source and assumption register, dataset list.

Run after scripts/grocery_wine_graphs.py has filled <package>/data and <package>/graphs:

    python -B scripts/grocery_wine_bundle_docs.py "<package folder>"

Writes, in the package folder:
  * data_dictionary.csv: every column of every CSV in data/ and the common columns of graphs/*.csv, with its unit and
    meaning. Columns are described by explicit entries first, then by naming rules (suffixes such as _usd or _pct);
    the script fails if a column matches neither, so the dictionary cannot fall behind the exports.
  * source_and_assumption_register.csv: every stated input of the three Utah models (U01-U18, the price-and-share
    grid's assumptions, F01-F23 and S01) and the data sources they rest on, with evidence standing and tested ranges.
  * datasets_regenerated.csv: the project's dataset exports and dashboard data regenerated by scripts/verify.bat, with
    size, modification time and SHA-256 (they stay in the project; they are too large to copy here).
Reads only local files.
"""

