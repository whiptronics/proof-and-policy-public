"""DABS wine sales and bottles for one fiscal year, from the monthly Sales Analysis Reports.

Writes web/src/lib/dabsWineBottles.generated.ts: gross wine sales, bottles sold and the average price per bottle, in
all sizes and in 750 ml, for fiscal year 2026 (July 2025 to June 2026, periods 1 to 12). Wine is every class whose
beverage group is "wine" in metadata/dabs_class_beverage_map.csv. The same-price page uses the average bottle price to
place a grocery store on DABS's package-agency compensation grid, which pays by bottles sold and average bottle price.

Gross sales are DABS's item-level sales in the report (state-store and package-agency sales, before sales tax, as the
report states them). The report's month totals are not checked against the annual report here.

Run:  python -B scripts/dabs_wine_bottles.py          (write the file)
      python -B scripts/dabs_wine_bottles.py --check  (exit 1 if the committed file differs)
The raw workbooks are found under ALCOHOL_DATA_HOME/data/raw (default: this checkout).
"""

from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from alcohol_data.paths import RAW_DIR  # noqa: E402

FISCAL_YEAR = 2026
OUT = ROOT / "web" / "src" / "lib" / "dabsWineBottles.generated.ts"
CLASS_MAP = ROOT / "metadata" / "dabs_class_beverage_map.csv"


def wine_classes() -> set[str]:
    with CLASS_MAP.open(encoding="utf-8", newline="") as f:
        return {r["class_code"] for r in csv.DictReader(f) if r["beverage_group"] == "wine"}


def asset_ids() -> list[str]:
    return [f"utah_dabs_sales_analysis_fy{FISCAL_YEAR}_p{p:02d}" for p in range(1, 13)]


def totals(raw: Path = RAW_DIR) -> dict[str, list[float]]:
    wine = wine_classes()
    tot: dict[str, list[float]] = defaultdict(lambda: [0.0, 0.0])
    for aid in asset_ids():
        files = sorted((raw / aid).glob("*.xlsx"))
        if len(files) != 1:
            raise FileNotFoundError(f"{aid}: expected one workbook in {raw / aid}, found {len(files)}")
        ws = openpyxl.load_workbook(files[0], read_only=True, data_only=True).worksheets[0]
        col: dict[str, int] | None = None
        for row in ws.iter_rows(values_only=True):
            if col is None:
                if row and "Class Code" in row:
                    col = {}
                    # The first "Total" is gross sales; the second is cases.
                    for i, v in enumerate(row):
                        if v is not None and v not in col:
                            col[v] = i
                continue
            if row[col["Class Code"]] not in wine:
                continue
            sales, bottles = row[col["Total"]], row[col["Bottle Count Sales"]]
            if not isinstance(sales, (int, float)) or not isinstance(bottles, (int, float)):
                continue
            size = str(row[col["Bottle Size"]])
            for key in ("all", size) if size == "750" else ("all",):
                tot[key][0] += sales
                tot[key][1] += bottles
        if col is None:
            raise ValueError(f"{aid}: no header row with 'Class Code'")
    return tot


def render(tot: dict[str, list[float]]) -> str:
    def obj(k: str) -> str:
        s, b = tot[k]
        return f"{{ sales: {round(s, 2)}, bottles: {round(b)}, averagePrice: {round(s / b, 4)} }}"

    ids = ", ".join(f'"{a}"' for a in asset_ids())
    return (
        "// Generated by scripts/dabs_wine_bottles.py from DABS's monthly Sales Analysis Reports; do not edit by hand.\n"
        "// tests/test_dabs_wine_bottles.py fails when this file differs from what the script writes.\n"
        f"export const DABS_WINE_BOTTLES = {{\n"
        f"  fiscalYear: {FISCAL_YEAR},\n"
        f"  sources: [{ids}],\n"
        f"  classes: {len(wine_classes())},\n"
        f"  all: {obj('all')},\n"
        f"  ml750: {obj('750')},\n"
        "} as const;\n"
    )


def main(argv: list[str]) -> int:
    text = render(totals())
    if "--check" in argv:
        same = OUT.read_text(encoding="utf-8") == text
        print("dabsWineBottles.generated.ts " + ("matches" if same else "DIFFERS from the raw reports"))
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
