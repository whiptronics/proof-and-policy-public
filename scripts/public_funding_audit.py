"""Write the Public Funding page's provenance audit and independent comparison table.

Usage: python scripts/public_funding_audit.py   (needs the pinned raw files; see docs/public-funding/qa/commands.md)

The provenance audit walks every source the page cites in the generated data and checks the pin, the raw file and
its SHA-256. The comparison table sets the page's Census-derived per-pupil figure beside USBE's own, district by
district. Both write Markdown under docs/public-funding/qa/.
"""

from __future__ import annotations

import hashlib
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import public_funding as pf  # noqa: E402

QA = pf.ROOT / "docs" / "public-funding" / "qa"


def sources(node, path="PF"):
    if isinstance(node, dict):
        if "asset" in node and "sha16" in node:
            yield path, node
        for k, v in node.items():
            yield from sources(v, f"{path}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from sources(v, f"{path}[{i}]")


def provenance(m: dict) -> tuple[str, int]:
    pins = pf._pins()
    rows, bad, seen = [], 0, {}
    for path, s in sources(m):
        seen.setdefault(s["asset"], []).append((path, s))
    for asset, uses in sorted(seen.items()):
        s = uses[0][1]
        pin = pins.get(asset)
        problems = []
        if pin is None:
            problems.append("no pin")
        else:
            if pin["sha256"][:16] != s["sha16"]:
                problems.append("sha16 differs from pin")
            if pin["url"] != s["url"]:
                problems.append("url differs from pin")
            try:
                f = pf.pinned(pf.RAW_DIR, asset)
                if hashlib.sha256(f.read_bytes()).hexdigest() != pin["sha256"]:
                    problems.append("file hash differs from pin")
            except FileNotFoundError:
                problems.append("raw file missing")
        bad += bool(problems)
        where = "; ".join(sorted({u[1]["locator"] for u in uses}))
        rows.append(
            f"| `{asset}` | {s['sha16']} | {s['retrieved']} | {len(uses)} | {where} | {'; '.join(problems) or 'ok'} |"
        )
    head = (
        "# Provenance audit: every source the Public Funding page cites\n\n"
        "Generated by `scripts/public_funding_audit.py` from `public_funding.measure()`, the same data the page is built\n"
        "from. For each cited asset it checks that a pin exists, that the page's 16-digit fingerprint and URL match the\n"
        "pin, and that the raw file's SHA-256 matches the pin. Machine-checked; nobody has reviewed it.\n\n"
        f"{len(seen)} assets, {sum(len(u) for u in seen.values())} citations, {bad} with problems.\n\n"
        "| Asset | SHA-256 (first 16) | Retrieved | Citations | Where | Check |\n| --- | --- | --- | --- | --- | --- |\n"
    )
    return head + "\n".join(rows) + "\n", bad


def comparison(m: dict) -> str:
    d = m["districts"]
    rows, ratios = [], []
    for s in d["systems"]:
        r = s["usbePerPupil"] / s["perPupil"] - 1
        ratios.append((r, s["enrollment"]))
        rows.append(
            f"| {s['name']} | {s['enrollment']:,} | ${s['perPupil']:,.0f} | ${s['usbePerPupil']:,} | {100 * r:+.1f}% |"
        )
    census = sum(s["currentSpending"] for s in d["systems"]) / sum(s["enrollment"] for s in d["systems"])
    big = [r for r, e in ratios if e >= 1000]
    fl = m["meals"]["freeLunchReimbursement"]
    return (
        "# Independent comparison: the page's figures beside a second source\n\n"
        "Generated by `scripts/public_funding_audit.py`. Machine-checked; nobody has reviewed it.\n\n"
        "## Current spending per pupil, FY2024 (Utah school year July 2023 to June 2024)\n\n"
        "The page computes per pupil from Census's FY2024 unit file (TCURELSC over V33, fall enrollment). USBE\n"
        "publishes its own figure from the Utah Public Education Financial System, under its own definition of\n"
        "current expenditures. The two are independent computations of a similar quantity, not the same number.\n\n"
        f"- All districts: Census-derived ${census:,.0f}; USBE district total ${d['usbe']['districtTotal']:,} "
        f"({100 * (d['usbe']['districtTotal'] / census - 1):+.1f}%). USBE statewide, charters included: "
        f"${d['usbe']['statewide']:,}.\n"
        f"- Median difference {100 * statistics.median(r for r, _ in ratios):+.1f}%; districts with 1,000 or more "
        f"students: largest {100 * max(abs(r) for r in big):.1f}% ({len(big)} districts). The test in "
        "`publicFunding.test.ts` holds that bound under 10%.\n"
        "- The largest gaps are in the smallest districts (Daggett, Piute, Tintic), where a few students or one\n"
        "  cost line moves the ratio.\n\n"
        "| District (Census name) | Fall enrollment | Census-derived | USBE | USBE vs Census |\n"
        "| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n\n"
        "## School meals money from liquor, three sources and three years\n\n"
        "| Source | Year | Amount |\n| --- | --- | --- |\n"
        f"| DABS 90th Annual Report, p. 32 (deposit) | FY2025 | ${m['dabs']['destinations'][[x['id'] for x in m['dabs']['destinations']].index('school_meals')]['amount'] / 1e6:,.3f}M |\n"
        f"| Legislature's School Meals Programs brief (Liquor Tax) | FY2024 | {m['meals']['fy2024']['liquorWords']} |\n"
        f"| S.B. 180 fiscal note (base appropriation) | FY2027 | ${m['meals']['fy2027LiquorBase'] / 1e6:,.1f}M |\n\n"
        "Different years and different bases (a deposit, a budget line, a base appropriation), so they are not\n"
        "expected to match; they agree on the scale (about $50 to $57 million a year).\n\n"
        "## Federal reimbursement for one free lunch, SY2024-25\n\n"
        f"89 FR 56720: Section 11 ${fl['section11']:.2f} plus Section 4 ${fl['section4']:.2f} = "
        f"${fl['section11'] + fl['section4']:.2f} in contiguous states (school food authorities under 60% free and\n"
        f"reduced-price), +${fl['section4HighNeedExtra']:.2f} at 60% or above, +${fl['performanceExtra']:.2f} if "
        "certified for the performance-based payment. A reimbursement rate, not a cost per meal; no second source\n"
        "was read for it.\n"
    )


def main() -> int:
    m = pf.measure()
    text, bad = provenance(m)
    (QA / "provenance-audit.md").write_text(text, encoding="utf-8")
    (QA / "independent-comparison.md").write_text(comparison(m), encoding="utf-8")
    print(f"wrote {QA / 'provenance-audit.md'} ({bad} problems) and {QA / 'independent-comparison.md'}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
